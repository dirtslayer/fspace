function Char.letter_to_frame(letter)
    local byte = string.byte(letter)
    if byte >= string.byte('a') and byte <= string.byte('z') then
        return byte - string.byte('a') + 1
    elseif byte >= string.byte('A') and byte <= string.byte('Z') then
        return byte - string.byte('A') + 1
    else
        return nil
    end
end

